import assert from 'node:assert/strict';
import { indexedDB } from 'fake-indexeddb';
globalThis.window = { indexedDB };
const { chooseUploadPersistence, sourceFingerprint, verifyUploadSource } = await import('../src/client/features/files/uploadSource.js');
const { saveStoredUpload, getStoredUploads, removeStoredUpload } = await import('../src/client/features/files/uploadQueueStore.js');
assert.equal(await chooseUploadPersistence({ size: 20 * 1024 ** 3 }), 'reselect');
const file = new File(['original'], 'photo.jpg', { lastModified: 10 });
assert.equal(await chooseUploadPersistence(file), 'copy');
const item = { id: 'large', accountId: 'test', file, fileName: file.name, sizeBytes: file.size, lastModified: 10, persistenceMode: 'reselect', sourceFingerprint: await sourceFingerprint(file), status: 'paused' };
await saveStoredUpload(item);
const [stored] = await getStoredUploads('test');
assert.equal(stored.file, null);
assert.equal(stored.persistenceMode, 'reselect');
await verifyUploadSource(stored, file);
await assert.rejects(verifyUploadSource(stored, new File(['modified'], 'photo.jpg', { lastModified: 10 })));
await removeStoredUpload(item.id);
await saveStoredUpload({ ...item, id: 'small', persistenceMode: 'copy' });
assert((await getStoredUploads('test'))[0].file);
console.log('Large uploads persist metadata only; small files remain recoverable; reselected source identity and sampled content validated.');
